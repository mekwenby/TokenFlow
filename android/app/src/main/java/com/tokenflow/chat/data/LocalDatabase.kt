@Entity(tableName = "providers")
data class ProviderEntity(
    @androidx.room.PrimaryKey val id: String,
    val name: String,
    val baseUrl: String,
    val protocol: String,
    val createdAt: Long,
    val updatedAt: Long,
)

@Entity(
    tableName = "models",
    foreignKeys = [ForeignKey(
        entity = ProviderEntity::class,
        parentColumns = ["id"],
        childColumns = ["providerId"],
        onDelete = ForeignKey.CASCADE,
    )],
    indices = [Index("providerId"), Index(value = ["providerId", "remoteId"])],
)
data class ModelEntity(
    @androidx.room.PrimaryKey val id: String,
    val providerId: String,
    val remoteId: String,
    val displayName: String,
    val maxOutputTokens: Int,
    val isDefault: Boolean,
    @ColumnInfo(defaultValue = "'UNKNOWN'") val visionStatus: String,
    val visionCheckedAt: Long?,
    val createdAt: Long,
    val updatedAt: Long,
)

@Entity(
    tableName = "conversations",
    foreignKeys = [ForeignKey(
        entity = ModelEntity::class,
        parentColumns = ["id"],
        childColumns = ["modelId"],
        onDelete = ForeignKey.SET_NULL,
    )],
    indices = [Index("modelId"), Index("updatedAt")],
)
data class ConversationEntity(
    @androidx.room.PrimaryKey val id: String,
    val title: String,
    val titleAutoGenerated: Boolean,
    val modelId: String?,
    @ColumnInfo(defaultValue = "'OVERRIDE'") val modelMode: String,
    val modelOverrideId: String?,
    val thinkingEffort: String,
    val systemPrompt: String,
    @ColumnInfo(defaultValue = "'OVERRIDE'") val systemPromptMode: String,
    val nickname: String,
    val userAvatar: String,
    @ColumnInfo(defaultValue = "'INHERIT'") val userAvatarMode: String,
    val assistantAvatar: String,
    @ColumnInfo(defaultValue = "'INHERIT'") val assistantAvatarMode: String,
    val urlReaderBackend: String?,
    val maxToolCalls: Int,
    @ColumnInfo(defaultValue = "1") val enableSearch: Boolean,
    @ColumnInfo(defaultValue = "1") val enableRead: Boolean,
    @ColumnInfo(defaultValue = "0") val enableKnowledge: Boolean,
    val pinnedAt: Long?,
    val archivedAt: Long?,
    val branchedFromConversationId: String?,
    val branchedFromMessageId: String?,
    val status: String,
    val statusMessage: String,
    val createdAt: Long,
    val updatedAt: Long,
    val lastMessageAt: Long?,
)

@Entity(tableName = "app_settings")
data class AppSettingsEntity(
    @androidx.room.PrimaryKey val id: Int = SINGLETON_ID,
    val systemPrompt: String = "",
    val userAvatar: String = "U",
    val assistantAvatar: String = "AI",
