sealed interface CanonicalContentPart {
    data class Text(val text: String) : CanonicalContentPart
    data class Image(val mimeType: String, val base64: String) : CanonicalContentPart
    data class Document(val fileName: String, val text: String) : CanonicalContentPart
}

data class CanonicalMessage(
    val role: String,
    val content: String = "",
    val parts: List<CanonicalContentPart> = emptyList(),
    val toolCalls: List<CanonicalToolCall> = emptyList(),
    val toolCallId: String? = null,
    val toolName: String? = null,
    val replayItems: List<ProtocolReplayItem> = emptyList(),
)

fun CanonicalMessage.contentParts(): List<CanonicalContentPart> = if (parts.isNotEmpty()) parts else {
    if (content.isEmpty()) emptyList() else listOf(CanonicalContentPart.Text(content))
}

