@Serializable
data class SerializableUsage(
    @SerialName("input_tokens") val inputTokens: Long = 0,
    @SerialName("output_tokens") val outputTokens: Long = 0,
    @SerialName("cache_read_tokens") val cacheReadTokens: Long = 0,
    @SerialName("cache_creation_tokens") val cacheCreationTokens: Long = 0,
) {
    fun toUsage() = Usage(inputTokens, outputTokens, cacheReadTokens, cacheCreationTokens)
}

fun Usage.serializable() = SerializableUsage(inputTokens, outputTokens, cacheReadTokens, cacheCreationTokens)

fun ChatMessage.assistantMetadata(json: Json): AssistantMetadata {
    if (metadata.isBlank()) return AssistantMetadata()
    return runCatching { json.decodeFromString<AssistantMetadata>(metadata) }.getOrDefault(AssistantMetadata())
}

